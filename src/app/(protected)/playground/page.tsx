'use client';

import { useState, useEffect } from 'react';
import { useEditor } from '@/frontend/hooks/useEditor';
import { useLanguage } from '@/frontend/hooks/useLanguage';
import MonacoEditor from '@/frontend/components/editor/MonacoEditor';
import EditorToolbar from '@/frontend/components/editor/EditorToolbar';
import OutputPanel from '@/frontend/components/editor/OutputPanel';
import CodeCriticPanel from '@/frontend/components/editor/CodeCriticPanel';
import MemoryVisualizer from '@/frontend/components/visualizer/MemoryVisualizer';
import { Sparkles, Layers } from 'lucide-react';
import { motion, AnimatePresence } from 'framer-motion';
import { LANGUAGES } from '@/config/languages';

export default function SandboxPlayground() {
  const { language, theme } = useLanguage();
  const {
    code,
    updateCode,
    output,
    isRunning,
    runCode,
    isReviewing,
    reviewCode,
    reviewResult,
    dryRunSteps,
    currentStepIndex,
    setCurrentStepIndex,
    isSimulated
  } = useEditor('sandbox');

  const handleExportReport = () => {
    const activeLang = LANGUAGES.find((l) => l.id === language) || LANGUAGES[0];
    const timestamp = new Date().toLocaleString();
    
    let markdown = `# Logic2Code AI - Study Guide & Execution Report\n\n`;
    markdown += `Generated on: **${timestamp}**  \n`;
    markdown += `Target Language: **${activeLang.name}**\n\n`;
    
    markdown += `## 1. Source Code\n\n`;
    markdown += `\`\`\`${activeLang.monacoLang || language}\n${code}\n\`\`\`\n\n`;
    
    markdown += `## 2. Execution Logs\n\n`;
    if (output) {
      markdown += `\`\`\`text\n${output}\n\`\`\`\n\n`;
    } else {
      markdown += `*No execution output logs available for this session.*\n\n`;
    }
    
    markdown += `## 3. Visualizer Dry-Run Trace\n\n`;
    if (dryRunSteps && dryRunSteps.length > 0) {
      markdown += `The following table traces the variable states across the execution steps:\n\n`;
      markdown += `| Step | Line | Variables / Scope State |\n`;
      markdown += `| :--- | :--- | :--- |\n`;
      dryRunSteps.forEach((step: any, index: number) => {
        const variablesStr = step.variables && Object.keys(step.variables).length > 0
          ? Object.entries(step.variables).map(([k, v]) => `\`${k}\` = \`${JSON.stringify(v)}\``).join(', ')
          : '*None*';
        markdown += `| ${index + 1} | Line ${step.line} | ${variablesStr} |\n`;
      });
      markdown += `\n`;
    } else {
      markdown += `*No dry-run execution steps recorded. Run code with output to generate trace.*\n\n`;
    }
    
    markdown += `## 4. AI Critic Feedback & Complexity Profile\n\n`;
    if (reviewResult) {
      markdown += `### Summary\n${reviewResult.review}\n\n`;
      markdown += `### Complexity Profile\n`;
      markdown += `- **Time Complexity:** \`${reviewResult.complexity.time}\` (${reviewResult.complexity.timeReason})\n`;
      markdown += `- **Space Complexity:** \`${reviewResult.complexity.space}\` (${reviewResult.complexity.spaceReason})\n\n`;
      
      if (reviewResult.annotations && reviewResult.annotations.length > 0) {
        markdown += `### Annotations\n`;
        reviewResult.annotations.forEach((ann: any) => {
          markdown += `- **Line ${ann.line}** [${ann.type.toUpperCase()}]: ${ann.message}\n`;
        });
        markdown += `\n`;
      }
      
      if (reviewResult.alternativeCode) {
        markdown += `### Recommended Optimization\n`;
        markdown += `\`\`\`${activeLang.monacoLang || language}\n${reviewResult.alternativeCode}\n\`\`\`\n\n`;
      }
    } else {
      markdown += `*No AI Critic feedback generated. Click "AI Review" to analyze code.*\n\n`;
    }
    
    markdown += `---\n*Generated by Logic2Code AI Playground.*`;

    const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `study_report_${language}_${new Date().toISOString().slice(0,10)}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const [activeRightTab, setActiveRightTab] = useState<'visualizer' | 'critic'>('visualizer');

  // Keyboard shortcut listener
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      const isCtrlOrCmd = e.ctrlKey || e.metaKey;
      
      if (isCtrlOrCmd && e.key === 'Enter') {
        e.preventDefault();
        if (!isRunning && !isReviewing) {
          runCode(code);
        }
      }
      
      if (isCtrlOrCmd && e.shiftKey && e.key.toLowerCase() === 'r') {
        e.preventDefault();
        if (!isRunning && !isReviewing) {
          setActiveRightTab('critic');
          reviewCode(code);
        }
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [code, isRunning, isReviewing, runCode, reviewCode]);

  return (
    <div className="flex-grow flex flex-col gap-4 py-2 h-[calc(100vh-120px)] lg:h-[calc(100vh-60px)] overflow-y-auto lg:overflow-hidden select-text pr-1 animate-fade-in">
      {/* Breadcrumb Header */}
      <div className="flex items-center justify-between border-b border-white/10 pb-3 select-none shrink-0">
        <div className="flex items-center gap-2">
          <span className="text-xs font-bold text-slate-100 uppercase tracking-wider">Sandbox Playground</span>
          <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full bg-blue-950/40 border border-blue-900/30 text-[9px] font-bold text-blue-400">
            <Sparkles className="w-2.5 h-2.5" />
            <span>Real-time execution</span>
          </span>
        </div>
        <span className="text-[10px] text-slate-400 font-bold font-mono">
          Language Mode: <strong className="text-blue-400 uppercase">{language}</strong>
        </span>
      </div>

      {/* Side-by-side IDE layout */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 flex-grow min-h-0 items-stretch overflow-y-auto lg:overflow-hidden pb-4">
        {/* Left Column: Editor & Output stacked vertically */}
        <div className="lg:col-span-7 flex flex-col h-full min-h-0">
          <motion.div
            layout
            initial={{ opacity: 0, y: 15 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ type: 'spring', stiffness: 120, damping: 15, delay: 0.08 }}
            className="flex-grow flex flex-col glass-spatial rounded-3xl overflow-hidden w-full transition-all duration-300 h-full min-h-0 border border-white/10 shadow-spatial-glow-blue/5 shadow-lg"
          >
            <EditorToolbar
              onRun={() => runCode(code)}
              isRunning={isRunning}
              onReview={() => {
                setActiveRightTab('critic');
                reviewCode(code);
              }}
              isReviewing={isReviewing}
              onExport={handleExportReport}
            />
            <div className="flex-grow p-4 overflow-y-auto custom-scrollbar flex flex-col gap-4 min-h-0 bg-slate-950/20 border-t border-white/5">
              <MonacoEditor 
                value={code} 
                onChange={updateCode} 
                executingLine={dryRunSteps.length > 0 && activeRightTab === 'visualizer' ? dryRunSteps[currentStepIndex]?.line : undefined}
                theme={theme}
              />
              <OutputPanel
                output={output}
                reviewResult={reviewResult ? reviewResult.review : null}
                onCloseReview={() => {}}
                isSimulated={isSimulated}
              />
            </div>
          </motion.div>
        </div>

        {/* Right Column: Visualizer & Critic inside tabbed card */}
        <div className="lg:col-span-5 flex flex-col gap-4 h-full min-h-0">
          {/* Sleek pill tab selector with sliding active background */}
          <div className="flex glass-spatial p-1.5 rounded-2xl w-fit shadow-sm select-none shrink-0 self-start relative border border-white/10">
            <button
              onClick={() => setActiveRightTab('visualizer')}
              className={`relative z-10 flex items-center gap-1.5 px-4 py-2 rounded-xl text-[10px] font-extrabold uppercase tracking-wider transition-colors duration-300 cursor-pointer ${
                activeRightTab === 'visualizer' ? 'text-white' : 'text-slate-400 hover:text-white'
              }`}
            >
              {activeRightTab === 'visualizer' && (
                <motion.div
                  layoutId="playground-active-tab"
                  className="absolute inset-0 bg-blue-600 border border-blue-500/20 rounded-xl shadow-md -z-10"
                  transition={{ type: 'spring', stiffness: 350, damping: 25 }}
                />
              )}
              <Layers className="w-3.5 h-3.5 text-blue-300" />
              <span>Execution Visualizer</span>
            </button>
            <button
              onClick={() => setActiveRightTab('critic')}
              className={`relative z-10 flex items-center gap-1.5 px-4 py-2 rounded-xl text-[10px] font-extrabold uppercase tracking-wider transition-colors duration-300 cursor-pointer ${
                activeRightTab === 'critic' ? 'text-white' : 'text-slate-400 hover:text-white'
              }`}
            >
              {activeRightTab === 'critic' && (
                <motion.div
                  layoutId="playground-active-tab"
                  className="absolute inset-0 bg-indigo-600 border border-indigo-500/20 rounded-xl shadow-md -z-10"
                  transition={{ type: 'spring', stiffness: 350, damping: 25 }}
                />
              )}
              <Sparkles className="w-3.5 h-3.5 text-indigo-300" />
              <span>AI Code Critic</span>
            </button>
          </div>

          {/* Panel Container */}
          <div className="flex-grow min-h-0 h-full">
            <AnimatePresence mode="wait">
              {activeRightTab === 'visualizer' ? (
                <motion.div
                  key="visualizer-tab"
                  initial={{ opacity: 0, y: 10 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0, y: -10 }}
                  transition={{ duration: 0.15 }}
                  className="h-full"
                >
                  <MemoryVisualizer
                    steps={dryRunSteps}
                    currentStepIndex={currentStepIndex}
                    onStepChange={setCurrentStepIndex}
                  />
                </motion.div>
              ) : (
                <motion.div
                  key="critic-tab"
                  initial={{ opacity: 0, y: 10 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0, y: -10 }}
                  transition={{ duration: 0.15 }}
                  className="h-full"
                >
                  <CodeCriticPanel
                    inline={true}
                    reviewResult={reviewResult}
                    isReviewing={isReviewing}
                    onClose={() => setActiveRightTab('visualizer')}
                    onApplyCode={updateCode}
                  />
                </motion.div>
              )}
            </AnimatePresence>
          </div>
        </div>
      </div>
    </div>
  );
}
